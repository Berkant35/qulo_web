/**
 * Builds `src/lib/constants/exampleQuestions.ts` from the app's own question
 * library in `qulo-server/src/data/seed/`.
 *
 * WHY IMPORT RATHER THAN WRITE: those questions are authored per market, not
 * translated — the Japanese set references 下北沢 and 東京タワー, the German set
 * the Rhine, the Arabic set the corniche. Hand-writing 16 locales of examples
 * would be strictly worse content, and copying them by hand would go stale the
 * moment the library changes. Re-run this script instead.
 *
 * SELECTION: two per category, in seed order, requiring four distinct answers.
 * Deterministic, so re-running produces the same file unless the library moved.
 *
 * Run: `npm run import:questions`
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const SEED_DIR = "../qulo-server/src/data/seed";
const OUT = "src/lib/constants/exampleQuestions.ts";
const PER_CATEGORY = 2;

const LOCALES = ["tr","en","de","fr","es","ar","ru","pt","it","ja","ko","zh","nl","pl","sv","hi"];

/** Category order on the page — broad interest first, niche last. */
const CATEGORIES = [
  "personality", "lifestyle", "travel", "food",
  "music", "film", "hobby", "humor", "sports", "technology", "fun",
];

if (!existsSync(SEED_DIR)) {
  console.error(`FAIL — ${SEED_DIR} not found. This script must run from web/ with qulo-server/ alongside it.`);
  process.exit(1);
}

const byLocale = {};
const missing = [];

for (const locale of LOCALES) {
  const path = join(SEED_DIR, `questions_${locale}.json`);
  if (!existsSync(path)) {
    missing.push(locale);
    continue;
  }
  const all = JSON.parse(readFileSync(path, "utf8"));
  const picked = [];

  for (const category of CATEGORIES) {
    const candidates = all.filter(
      (q) =>
        q.category === category &&
        Array.isArray(q.answers) &&
        q.answers.length === 4 &&
        new Set(q.answers).size === 4 &&
        q.question_text.trim().length > 0,
    );
    for (const question of candidates.slice(0, PER_CATEGORY)) {
      picked.push({
        category,
        question: question.question_text.trim(),
        answers: question.answers.map((a) => a.trim()),
      });
    }
  }
  byLocale[locale] = picked;
}

if (missing.length) {
  console.error(`FAIL — no seed file for: ${missing.join(", ")}`);
  process.exit(1);
}

const counts = LOCALES.map((l) => byLocale[l].length);
const min = Math.min(...counts);
if (min < CATEGORIES.length) {
  console.error(`FAIL — a locale yielded only ${min} questions; every category must contribute.`);
  process.exit(1);
}

const body = LOCALES.map((locale) => {
  const entries = byLocale[locale]
    .map(
      (q) =>
        `    {\n      category: ${JSON.stringify(q.category)},\n      question: ${JSON.stringify(q.question)},\n      answers: ${JSON.stringify(q.answers)},\n    },`,
    )
    .join("\n");
  return `  ${locale}: [\n${entries}\n  ],`;
}).join("\n");

writeFileSync(
  OUT,
  `/**
 * Example questions shown on /[locale]/questions.
 *
 * GENERATED by \`npm run import:questions\` from the app's own question library
 * (\`qulo-server/src/data/seed/questions_<locale>.json\`). Do not edit by hand —
 * re-run the script. Each locale's set is authored for that market rather than
 * translated, which is the whole reason this is imported instead of written.
 *
 * Two per category, four distinct answer options each.
 */
export interface ExampleQuestion {
  category: string;
  question: string;
  answers: string[];
}

/** Category order on the page. */
export const QUESTION_CATEGORIES = ${JSON.stringify(CATEGORIES, null, 2).replace(/\n/g, "\n")} as const;

export const EXAMPLE_QUESTIONS: Record<string, ExampleQuestion[]> = {
${body}
};
`,
);

console.log(
  `OK — ${OUT}\n   ${LOCALES.length} locales · ${CATEGORIES.length} categories · ${counts[0]} questions each`,
);
